import { createHash } from 'node:crypto';

/**
 * Группировка анонимных клиентов без хранения настоящего IP (TECH-SPEC.md §6:
 * лимит частоты и лимит одновременности гостя — оба «по хешу IP»). Без соли —
 * значение нигде не хранится и не сравнивается как секрет, только ключ
 * группировки в памяти процесса; не тот же контекст, что хеш пароля.
 */
export function hashIp(ip: string): string {
  return createHash('sha256').update(ip).digest('hex');
}
