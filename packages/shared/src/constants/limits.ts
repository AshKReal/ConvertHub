/**
 * Спека 018 (TECH-SPEC.md §9). DOCX — это ZIP: защита от бомбы распаковки.
 * Отклоняем, если несжатый размер содержимого больше `MAX_DOCX_UNZIP_RATIO`×
 * размера файла ЛИБО больше `MAX_DOCX_UNZIP_BYTES` абсолютно.
 *
 * Меряется ФАКТИЧЕСКАЯ распаковка, а не заявленная в заголовках (🔒 BE-DOCX-01):
 * числа в центральном каталоге пишет тот же, кто прислал файл.
 *
 * 50 МиБ (было 200) — число связано с тремя другими, и менять его в одиночку
 * нельзя (BE-DOCX-04):
 * - `mem_limit: 1g` у Gotenberg в `docker-compose.yml`, `DOCUMENT_POOL_SIZE` = 8
 *   параллельных конвертаций в этот контейнер. LibreOffice разворачивает XML в
 *   память с коэффициентом 3–10×, так что 8 × 200 МиБ гарантировали OOM-kill на
 *   честном документе, а не на вредоносном.
 * - Сама проверка считается ДО взятия слота пула, то есть пулом не ограничена:
 *   потолок — это ещё и объём работы, который посторонний может заказать одним
 *   запросом. 50 МиБ распаковки дёшевы, 200 МиБ — уже вектор нагрузки.
 * Реальный `.docx` на 50 МиБ несжатого — книга с иллюстрациями; при 10 МиБ
 * лимита на загрузку это коэффициент 5:1, вдвое ниже потолка коэффициента.
 */
export const MAX_DOCX_UNZIP_RATIO = 100;
export const MAX_DOCX_UNZIP_BYTES = 50 * 1024 * 1024;
